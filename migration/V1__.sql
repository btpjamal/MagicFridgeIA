CREATE TABLE categoria
(
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nome VARCHAR(255),
    CONSTRAINT pk_categoria PRIMARY KEY (id)
);

CREATE TABLE food
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nome       VARCHAR(255),
    quantidade INT,
    validade   date,
    categoria  BIGINT,
    CONSTRAINT pk_food PRIMARY KEY (id)
);

